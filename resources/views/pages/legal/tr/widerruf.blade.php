<h2>Mesafeli sözleşmelerde cayma hakkı</h2>
<p>
    Tüketiciler, mesafeli olarak kurulan sözleşmelerde kural olarak 14 gün içinde gerekçe
    göstermeksizin sözleşmeden cayma hakkına sahiptir.
</p>

<h2>İstisna: ölçüye özel üretim</h2>
<p>
    Müşteri özelliklerine göre üretilen ya da açıkça kişisel ihtiyaçlara göre hazırlanan
    ürünlerin teslimine ilişkin sözleşmelerde cayma hakkı <strong>yoktur</strong>. Fon perde,
    plise, stor, jaluzi ve ölçüye özel halılar pencerenize veya odanıza göre üretildiğinden,
    üretim başladıktan sonra cayma mümkün değildir.
</p>

<h2>Üretim başlamadan iptal</h2>
<p>
    Üretim henüz başlamamışsa siparişi iptal edebilirsiniz. Oluşmuş masrafları (örn. sipariş
    edilmiş özel kumaşlar) faturalandırabiliriz.
</p>

<h2>Stok ürünler</h2>
<p>
    Ölçüye özel olmayan stok ürünlerde (örn. standart ölçülerde hazır halılar) ürünün teslim
    alınmasından itibaren 14 günlük yasal cayma hakkı geçerlidir.
</p>

