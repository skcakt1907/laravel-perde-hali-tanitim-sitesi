<h2>Caymanın sonuçları</h2>
<p>
    Geçerli bir cayma hâlinde, alınan tüm ödemeleri gecikmeksizin, en geç cayma bildiriminin
    veya iade edilen ürünün bize ulaşmasından itibaren 14 gün içinde geri öderiz.
</p>
