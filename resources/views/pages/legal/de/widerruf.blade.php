<h2>Widerrufsrecht bei Fernabsatzverträgen</h2>
<p>
    Verbraucher haben bei im Fernabsatz geschlossenen Verträgen grundsätzlich das Recht,
    den Vertrag binnen 14 Tagen ohne Angabe von Gründen zu widerrufen.
</p>

<h2>Ausnahme: Maßanfertigung</h2>
<p>
    Das Widerrufsrecht besteht <strong>nicht</strong> bei Verträgen zur Lieferung von Waren,
    die nach Kundenspezifikation angefertigt werden oder eindeutig auf die persönlichen
    Bedürfnisse zugeschnitten sind. Da Gardinen, Plissees, Rollos, Jalousien und
    Maßteppiche auf Ihr Fenster bzw. Ihren Raum gefertigt werden, ist ein Widerruf nach
    Fertigungsbeginn ausgeschlossen.
</p>

<h2>Widerruf vor Fertigungsbeginn</h2>
<p>
    Solange die Fertigung noch nicht begonnen hat, können Sie den Auftrag stornieren.
    Bereits angefallene Kosten (z. B. bestellte Sonderstoffe) können wir in Rechnung stellen.
</p>

<h2>Lagerware</h2>
<p>
    Für nicht maßgefertigte Lagerware (z. B. Standardteppiche in Standardgrößen) gilt das
    gesetzliche Widerrufsrecht von 14 Tagen ab Erhalt der Ware.
</p>

<h2>Ausübung des Widerrufs</h2>
<p>
    Um Ihr Widerrufsrecht auszuüben, informieren Sie uns mittels einer eindeutigen Erklärung
    per E-Mail an {{ setting('eposta') }} oder telefonisch unter {{ setting('telefon') }}.
    Anschrift: {{ setting('firma_unvan', setting('site_adi')) }}, {{ setting('adres') }}.
</p>

<h2>Folgen des Widerrufs</h2>
<p>
    Im Fall eines wirksamen Widerrufs erstatten wir alle erhaltenen Zahlungen unverzüglich,
    spätestens binnen 14 Tagen nach Eingang der Widerrufserklärung bzw. der zurückgesandten
    Ware.
</p>
