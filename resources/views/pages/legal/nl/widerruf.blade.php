<h2>Herroepingsrecht bij overeenkomsten op afstand</h2>
<p>
    Bij overeenkomsten die op afstand worden gesloten, hebben consumenten in het algemeen het
    recht de overeenkomst binnen 14 dagen zonder opgave van redenen te herroepen.
</p>

<h2>Uitzondering: maatwerk</h2>
<p>
    Er bestaat <strong>geen</strong> herroepingsrecht bij overeenkomsten voor de levering van
    zaken die volgens specificaties van de klant zijn vervaardigd of duidelijk op persoonlijke
    wensen zijn afgestemd. Omdat gordijnen, plissé- en rolgordijnen, jaloezieën en tapijten op
    maat voor uw specifieke raam of ruimte worden geproduceerd, is herroeping uitgesloten zodra
    de productie is begonnen.
</p>

<h2>Annuleren voordat de productie begint</h2>
<p>
    Zolang de productie nog niet is gestart, kunt u de opdracht annuleren. Al gemaakte kosten
    (bijvoorbeeld speciaal bestelde stoffen) mogen wij in rekening brengen.
</p>

<h2>Voorraadartikelen</h2>
<p>
    Voor artikelen die niet op maat worden gemaakt (bijvoorbeeld tapijten in standaardmaten)
    geldt het wettelijke herroepingsrecht van 14 dagen vanaf ontvangst van de zaken.
</p>

<h2>Uitoefening van het herroepingsrecht</h2>
<p>
    Om uw herroepingsrecht uit te oefenen, informeert u ons met een duidelijke verklaring per
    e-mail via {{ setting('eposta') }} of telefonisch via {{ setting('telefon') }}.
    Adres: {{ setting('firma_unvan', setting('site_adi')) }}, {{ setting('adres') }}.
</p>

<h2>Gevolgen van de herroeping</h2>
<p>
    Bij een geldige herroeping betalen wij alle ontvangen betalingen onverwijld terug, en
    uiterlijk binnen 14 dagen nadat wij de herroepingsverklaring of de teruggezonden zaken
    hebben ontvangen.
</p>
