<h2>Wat zijn cookies?</h2>
<p>
    Cookies zijn kleine tekstbestanden die uw browser op uw apparaat opslaat. Zij maken het
    mogelijk een sessie te herkennen en formulieren tegen misbruik te beschermen.
</p>

