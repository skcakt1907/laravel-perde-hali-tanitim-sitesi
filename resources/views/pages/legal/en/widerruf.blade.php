<h2>Right of withdrawal for distance contracts</h2>
<p>
    For contracts concluded at a distance, consumers generally have the right to withdraw from
    the contract within 14 days without giving any reason.
</p>

<h2>Exception: made-to-measure goods</h2>
<p>
    There is <strong>no</strong> right of withdrawal for contracts for the supply of goods made
    to the customer's specifications or clearly tailored to personal requirements. As curtains,
    pleated blinds, roller blinds, venetian blinds and made-to-measure rugs are produced for
    your specific window or room, withdrawal is excluded once production has begun.
</p>

<h2>Cancellation before production begins</h2>
<p>
    As long as production has not yet started, you may cancel the order. We may invoice costs
    already incurred (for example special fabrics that have been ordered).
</p>

<h2>Stock items</h2>
<p>
    For items that are not made to measure (for example standard-size rugs), the statutory
    14-day right of withdrawal applies from receipt of the goods.
</p>

<h2>Exercising the right of withdrawal</h2>
<p>
    To exercise your right of withdrawal, inform us by means of a clear statement by e-mail to
    {{ setting('eposta') }} or by phone on {{ setting('telefon') }}.
    Address: {{ setting('firma_unvan', setting('site_adi')) }}, {{ setting('adres') }}.
</p>

<h2>Consequences of withdrawal</h2>
<p>
    In the event of a valid withdrawal we will refund all payments received without delay, and
    at the latest within 14 days of receiving the withdrawal statement or the returned goods.
</p>
